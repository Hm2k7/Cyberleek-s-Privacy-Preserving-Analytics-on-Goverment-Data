"""
Dataset Validation Script
Validates the synthetic healthcare dataset generated by generate_dataset.py.
Runs comprehensive checks on schema, distributions, correlations, and missing data.

Usage: python validate_dataset.py
"""

import os
import sys
import pandas as pd
import numpy as np


def print_result(check_name: str, passed: bool, message: str = "") -> bool:
    """Print a check result with pass/fail status."""
    status = "✅ PASS" if passed else "❌ FAIL"
    if message:
        print(f"  [{status}] {check_name}: {message}")
    else:
        print(f"  [{status}] {check_name}")
    return passed


def main():
    print("=" * 60)
    print("  SYNTHETIC DATASET VALIDATION")
    print("  Privacy-Preserving Analytics on Sensitive Government Data")
    print("=" * 60)

    base_dir = os.path.dirname(os.path.abspath(__file__))
    data_dir = os.path.join(base_dir, "data")

    files = {
        "A": os.path.join(data_dir, "hospital_a_abu_dhabi.csv"),
        "B": os.path.join(data_dir, "hospital_b_dubai.csv"),
        "C": os.path.join(data_dir, "hospital_c_rak.csv"),
    }

    checks_passed = 0
    total_checks = 0

    def run_check(name, condition, msg=""):
        nonlocal checks_passed, total_checks
        total_checks += 1
        if print_result(name, condition, msg):
            checks_passed += 1

    # ── 1. Schema Validation ──────────────────────────────────────
    print("\n── 1. Schema Validation ──")

    files_exist = all(os.path.exists(f) for f in files.values())
    run_check("All 3 CSV files exist in data/ directory", files_exist,
              ", ".join(f"{k}: {'found' if os.path.exists(v) else 'MISSING'}" for k, v in files.items()))

    if not files_exist:
        print("\n❌ Missing data files. Run 'python generate_dataset.py' first.")
        sys.exit(1)

    try:
        dfs = {k: pd.read_csv(v) for k, v in files.items()}
    except (pd.errors.EmptyDataError, pd.errors.ParserError) as e:
        print(f"\n❌ Could not read a data file ({e}). "
              "Data may be corrupted — try regenerating with 'python generate_dataset.py'.")
        sys.exit(1)

    if any(df.empty for df in dfs.values()):
        empty = [k for k, df in dfs.items() if df.empty]
        print(f"\n❌ Data file(s) for hospital(s) {empty} have no rows. "
              "Try regenerating with 'python generate_dataset.py'.")
        sys.exit(1)

    df_all = pd.concat(dfs.values(), ignore_index=True)

    core_columns = [
        "patient_id", "age", "gender", "nationality", "bmi", "has_diabetes",
        "has_hypertension", "has_obesity", "smoking_status",
        "blood_pressure_systolic", "blood_pressure_diastolic", "hba1c",
        "admission_date", "discharge_date", "length_of_stay", "readmitted_30_days"
    ]

    for h_name, df in dfs.items():
        missing_core = [col for col in core_columns if col not in df.columns]
        run_check(f"Hospital {h_name} core columns present",
                  len(missing_core) == 0,
                  f"Missing: {missing_core}" if missing_core else "All 16 core columns present")

    extra_a = [col for col in ["insurance_type", "cholesterol_total"] if col not in dfs["A"].columns]
    run_check("Hospital A extra columns (insurance_type, cholesterol_total)",
              len(extra_a) == 0, f"Missing: {extra_a}" if extra_a else "Present")

    extra_b = [col for col in ["insurance_type", "emergency_admission"] if col not in dfs["B"].columns]
    run_check("Hospital B extra columns (insurance_type, emergency_admission)",
              len(extra_b) == 0, f"Missing: {extra_b}" if extra_b else "Present")

    extra_c = [col for col in ["referral_source"] if col not in dfs["C"].columns]
    run_check("Hospital C extra columns (referral_source)",
              len(extra_c) == 0, f"Missing: {extra_c}" if extra_c else "Present")

    # ── 2. No Overlapping Patient IDs ─────────────────────────────
    print("\n── 2. Patient ID Uniqueness ──")

    ids_a = set(dfs["A"]["patient_id"])
    ids_b = set(dfs["B"]["patient_id"])
    ids_c = set(dfs["C"]["patient_id"])
    overlap_ab = ids_a & ids_b
    overlap_bc = ids_b & ids_c
    overlap_ac = ids_a & ids_c
    no_overlap = len(overlap_ab) == 0 and len(overlap_bc) == 0 and len(overlap_ac) == 0
    run_check("No overlapping patient IDs across hospitals", no_overlap,
              f"Overlaps: A∩B={len(overlap_ab)}, B∩C={len(overlap_bc)}, A∩C={len(overlap_ac)}")

    # ── 3. Record Counts ──────────────────────────────────────────
    print("\n── 3. Record Counts ──")

    run_check("Hospital A record count (~8,000)",
              7500 <= len(dfs["A"]) <= 8500, f"Count: {len(dfs['A']):,}")
    run_check("Hospital B record count (~5,000)",
              4500 <= len(dfs["B"]) <= 5500, f"Count: {len(dfs['B']):,}")
    run_check("Hospital C record count (~2,000)",
              1500 <= len(dfs["C"]) <= 2500, f"Count: {len(dfs['C']):,}")
    total = len(df_all)
    run_check("Total record count (~15,000)",
              14000 <= total <= 16000, f"Total: {total:,}")

    # ── 4. Distribution Checks ────────────────────────────────────
    print("\n── 4. Distribution Checks ──")

    national_diabetes = df_all["has_diabetes"].mean()
    run_check("National diabetes prevalence (16-28%)",
              0.16 <= national_diabetes <= 0.28, f"Rate: {national_diabetes:.1%}")

    prev_a = dfs["A"]["has_diabetes"].mean()
    prev_b = dfs["B"]["has_diabetes"].mean()
    prev_c = dfs["C"]["has_diabetes"].mean()
    run_check("Hospital A highest diabetes prevalence",
              prev_a > prev_b and prev_a > prev_c,
              f"A={prev_a:.1%}, B={prev_b:.1%}, C={prev_c:.1%}")

    national_readmission = df_all["readmitted_30_days"].mean()
    run_check("National readmission rate (10-25%)",
              0.10 <= national_readmission <= 0.25, f"Rate: {national_readmission:.1%}")

    mean_age = df_all["age"].mean()
    min_age = df_all["age"].min()
    max_age = df_all["age"].max()
    run_check("Age range (18-95)",
              min_age >= 18 and max_age <= 95, f"Range: {min_age}-{max_age}, Mean: {mean_age:.1f}")

    mean_bmi = df_all["bmi"].mean()
    min_bmi = df_all["bmi"].min()
    max_bmi = df_all["bmi"].max()
    run_check("BMI range (16-50, mean 25-32)",
              16 <= min_bmi and max_bmi <= 50 and 25 <= mean_bmi <= 32,
              f"Range: {min_bmi:.1f}-{max_bmi:.1f}, Mean: {mean_bmi:.1f}")

    # Gender — generator uses 'M'/'F'
    male_ratio = (df_all["gender"] == "M").mean()
    run_check("Gender split (50-60% male)",
              0.50 <= male_ratio <= 0.60, f"Male ratio: {male_ratio:.1%}")

    smoker_ratio = (df_all["smoking_status"] == "Current").mean()
    run_check("Smoking (8-25% current)",
              0.08 <= smoker_ratio <= 0.25, f"Current smoker ratio: {smoker_ratio:.1%}")

    min_bp = df_all["blood_pressure_systolic"].min()
    max_bp = df_all["blood_pressure_systolic"].max()
    run_check("BP systolic range (90-200)",
              90 <= min_bp and max_bp <= 200, f"Range: {min_bp}-{max_bp}")

    hba1c_clean = df_all["hba1c"].dropna()
    min_hba1c = hba1c_clean.min()
    max_hba1c = hba1c_clean.max()
    run_check("HbA1c range (4.0-14.0)",
              4.0 <= min_hba1c and max_hba1c <= 14.0,
              f"Range: {min_hba1c:.1f}-{max_hba1c:.1f}")

    # ── 5. Correlation Checks ─────────────────────────────────────
    print("\n── 5. Correlation Checks ──")

    corr_diab_age = df_all["has_diabetes"].astype(float).corr(df_all["age"].astype(float))
    run_check("Diabetes positively correlated with age (r > 0.15)",
              corr_diab_age > 0.15, f"r = {corr_diab_age:.3f}")

    corr_diab_bmi = df_all["has_diabetes"].astype(float).corr(df_all["bmi"].astype(float))
    run_check("Diabetes positively correlated with BMI (r > 0.1)",
              corr_diab_bmi > 0.1, f"r = {corr_diab_bmi:.3f}")

    corr_hyp_age = df_all["has_hypertension"].astype(float).corr(df_all["age"].astype(float))
    run_check("Hypertension positively correlated with age (r > 0.15)",
              corr_hyp_age > 0.15, f"r = {corr_hyp_age:.3f}")

    mean_hba1c_diab = df_all[df_all["has_diabetes"] == True]["hba1c"].mean()
    mean_hba1c_non = df_all[df_all["has_diabetes"] == False]["hba1c"].mean()
    run_check("HbA1c higher for diabetics vs non-diabetics",
              mean_hba1c_diab > mean_hba1c_non,
              f"Diabetic: {mean_hba1c_diab:.2f}, Non-diabetic: {mean_hba1c_non:.2f}")

    mean_bp_hyp = df_all[df_all["has_hypertension"] == True]["blood_pressure_systolic"].mean()
    mean_bp_non = df_all[df_all["has_hypertension"] == False]["blood_pressure_systolic"].mean()
    run_check("BP systolic higher for hypertensive vs normotensive",
              mean_bp_hyp > mean_bp_non,
              f"Hypertensive: {mean_bp_hyp:.1f}, Normotensive: {mean_bp_non:.1f}")

    # ── 6. Missing Data Checks ────────────────────────────────────
    print("\n── 6. Missing Data Checks ──")

    hba1c_missing = df_all["hba1c"].isna().mean()
    run_check("HbA1c has missing values (3-12%)",
              0.03 <= hba1c_missing <= 0.12, f"Missing: {hba1c_missing:.1%}")

    core_no_missing = ["age", "gender", "patient_id", "has_diabetes", "has_hypertension"]
    for col in core_no_missing:
        run_check(f"Core field '{col}' has 0% missing",
                  df_all[col].isna().sum() == 0)

    # ── 7. Internal Consistency Checks ────────────────────────────
    print("\n── 7. Internal Consistency Checks ──")

    for h_name, df in dfs.items():
        dup_ids = df["patient_id"].duplicated().sum()
        run_check(f"Hospital {h_name} no duplicate patient IDs within file",
                  dup_ids == 0, f"Duplicates: {dup_ids}")

    admit_dt = pd.to_datetime(df_all["admission_date"])
    discharge_dt = pd.to_datetime(df_all["discharge_date"])

    date_violations = (discharge_dt < admit_dt).sum()
    run_check("Discharge date always on/after admission date",
              date_violations == 0, f"Violations: {date_violations}")

    computed_los = (discharge_dt - admit_dt).dt.days
    los_mismatch = (computed_los != df_all["length_of_stay"]).sum()
    run_check("length_of_stay matches (discharge_date - admission_date)",
              los_mismatch == 0, f"Mismatches: {los_mismatch}")

    obesity_mismatch = ((df_all["bmi"] >= 30.0) != df_all["has_obesity"]).sum()
    run_check("has_obesity flag matches bmi >= 30.0",
              obesity_mismatch == 0, f"Mismatches: {obesity_mismatch}")

    bp_violations = (df_all["blood_pressure_systolic"] <= df_all["blood_pressure_diastolic"]).sum()
    run_check("Systolic BP always greater than diastolic BP",
              bp_violations == 0, f"Violations: {bp_violations}")

    bp_gap_violations = ((df_all["blood_pressure_systolic"] - df_all["blood_pressure_diastolic"]) < 25).sum()
    run_check("Systolic-diastolic BP gap always >= 25",
              bp_gap_violations == 0, f"Violations: {bp_gap_violations}")

    date_range_violations = ((admit_dt.dt.year < 2024) | (admit_dt.dt.year > 2025)).sum()
    run_check("Admission dates within intended 2024-2025 window",
              date_range_violations == 0, f"Violations: {date_range_violations}")

    hba1c_missing_diab = df_all[df_all["has_diabetes"] == True]["hba1c"].isna().mean()
    hba1c_missing_non = df_all[df_all["has_diabetes"] == False]["hba1c"].isna().mean()
    run_check("HbA1c missingness lower for diabetics (more frequently tested)",
              hba1c_missing_diab < hba1c_missing_non,
              f"Diabetic missing: {hba1c_missing_diab:.1%}, Non-diabetic missing: {hba1c_missing_non:.1%}")

    # ── Summary ───────────────────────────────────────────────────
    print("\n" + "=" * 60)
    print(f"  VALIDATION RESULT: {checks_passed}/{total_checks} checks passed")
    if checks_passed == total_checks:
        print("  ✅ ALL CHECKS PASSED")
    else:
        print(f"  ❌ {total_checks - checks_passed} CHECK(S) FAILED")
    print("=" * 60)

    # ── 8. Ground Truth Statistics ────────────────────────────────
    print("\n" + "=" * 60)
    print("  GROUND TRUTH STATISTICS")
    print("  (Reference values for Person 2, 3, and 4)")
    print("=" * 60)
    print(f"  Total records:                   {total:,}")
    print(f"  Hospital A (Abu Dhabi):           {len(dfs['A']):,} records")
    print(f"  Hospital B (Dubai):               {len(dfs['B']):,} records")
    print(f"  Hospital C (RAK):                 {len(dfs['C']):,} records")
    print()
    print(f"  National diabetes prevalence:     {national_diabetes:.2%}")
    print(f"    Hospital A (Abu Dhabi):          {prev_a:.2%}")
    print(f"    Hospital B (Dubai):              {prev_b:.2%}")
    print(f"    Hospital C (RAK):                {prev_c:.2%}")
    print()
    nat_hyp = df_all["has_hypertension"].mean()
    print(f"  National hypertension prevalence: {nat_hyp:.2%}")
    print(f"  National readmission rate:        {national_readmission:.2%}")
    print()
    print(f"  Mean HbA1c (diabetic):            {mean_hba1c_diab:.2f}")
    print(f"  Mean HbA1c (non-diabetic):        {mean_hba1c_non:.2f}")
    print(f"  Mean BP systolic (hypertensive):  {mean_bp_hyp:.1f}")
    print(f"  Mean BP systolic (normotensive):  {mean_bp_non:.1f}")
    print(f"  Mean age:                         {mean_age:.1f}")
    print(f"  Mean BMI:                         {mean_bmi:.1f}")
    print(f"  Male ratio:                       {male_ratio:.1%}")
    print(f"  Current smoker ratio:             {smoker_ratio:.1%}")
    print("=" * 60)

    sys.exit(0 if checks_passed == total_checks else 1)


if __name__ == "__main__":
    main()
